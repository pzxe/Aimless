// Snapshot of Valorant's official competitive tiers (names, colours and icons) from valorant-api.com
// (keyless). Bundled so the rank pickers and icons work offline; the app also refreshes the data at runtime.
//   node scripts/fetch-valorant-tiers.mjs
import { mkdir, writeFile } from 'node:fs/promises'

const res = await fetch('https://valorant-api.com/v1/competitivetiers')
if (!res.ok) throw new Error(`valorant-api.com answered ${res.status}`)
const { data } = await res.json()
const latest = data[data.length - 1]
const tiers = latest.tiers.filter((t) => t.tier >= 3 && t.smallIcon)
await mkdir('public/rank-icons/valorant', { recursive: true })
const rows = []
for (const t of tiers) {
  const img = await fetch(t.smallIcon)
  if (!img.ok) throw new Error(`icon ${t.tier}: ${img.status}`)
  await writeFile(`public/rank-icons/valorant/${t.tier}.png`, Buffer.from(await img.arrayBuffer()))
  const name = t.tierName.toLowerCase().replace(/(^|\s)\S/g, (c) => c.toUpperCase())
  rows.push({ tier: t.tier, name, division: t.divisionName.toLowerCase(), color: `#${t.color.slice(0, 6)}` })
}
await writeFile(
  'src/data/valorantTiers.ts',
  `// Generated by scripts/fetch-valorant-tiers.mjs from valorant-api.com (episode data set ${latest.uuid}).\n` +
    `export interface ValorantTier { tier: number; name: string; division: string; color: string }\n` +
    `export const VALORANT_TIERS: readonly ValorantTier[] = ${JSON.stringify(rows, null, 2)}\n`,
)
console.log(`${rows.length} tiers saved (${rows[0].name} … ${rows.at(-1).name})`)
